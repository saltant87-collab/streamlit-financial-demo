def render_term_panel(key: str, ui: Any, *, expanded: bool = False) -> None:
    """在圖表旁顯示名詞解說（expander）。"""
    title, body = TERMS[key]
    with ui.expander(f"📖 {title}怎麼看？", expanded=expanded):
        ui.markdown(body.strip())


def render_chart_with_help(
    key: str,
    render_chart_fn,
    ui: Any,
    *,
    show_help: bool = True,
    chart_ratio: int = 3,
    help_ratio: int = 2,
) -> None:
    """左圖右文：chart_ratio : help_ratio。"""
    if not show_help:
        render_chart_fn(ui)
        return
    left, right = ui.columns([chart_ratio, help_ratio])
    with left:
        render_chart_fn(left)
    with right:
        title, body = TERMS[key]
        right.markdown(f"**{title}**")
        right.markdown(body.strip())
